def _fixture_cases() -> list[Case]:
    out = []
    for case, expect in _FIXTURE_EXPECT.items():
        texts = set()
        for f in sorted((_BACKEND / "eval_fixtures" / case / "cache" / "llm").glob("*.json")):
            r = json.loads(f.read_text(encoding="utf-8")).get("result")
            if isinstance(r, dict) and isinstance(r.get("payment_clause_text"), dict):
                v = r["payment_clause_text"].get("value")
                if v:
                    texts.add(v)
        for i, t in enumerate(sorted(texts)):
            out.append(Case(f"{case}" + (f"#{i}" if i else ""), "fixture", t, expect))
    return out


